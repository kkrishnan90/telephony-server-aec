package com.telephony.aec;

import java.util.ArrayDeque;
import java.util.Deque;
import java.util.Objects;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentMap;

/**
 * Thread-safe Server-Side Acoustic Echo Cancellation Pipeline Service.
 *
 * <p>Designed to be embedded as a library interceptor in backend audio pipelines
 * between an 8 kHz telephony gateway (RTP / G.711 u-law / G.711 A-law / PCM16LE)
 * and a real-time conversational AI model (16 kHz PCM16LE input, 24 kHz PCM16LE output):
 * <ul>
 *   <li><b>Outbound Hook (Model -> Telephony):</b> Accepts 24 kHz (or 8 kHz) PCM16LE from the model,
 *       downsamples to 8 kHz, registers the reference frames in the call session's AEC buffer,
 *       and returns 8 kHz PCM16LE or G.711 u-law bytes to transmit to the telephony leg.</li>
 *   <li><b>Inbound Hook (Telephony -> Model):</b> Accepts 8 kHz PCM16LE or G.711 u-law from the caller,
 *       cancels acoustic/hybrid echo against the buffered far-end reference, upsamples 1:2 to 16 kHz PCM16LE,
 *       and returns the clean {@code byte[]} ready to send to the model.</li>
 * </ul>
 */
public final class TelephonyAecPipelineService {

    private final ConcurrentMap<String, CallSessionContext> sessions = new ConcurrentHashMap<>();

    public void registerCallSession(String callId) {
        registerCallSession(callId, AecConfig.defaults());
    }

    public void registerCallSession(String callId, AecConfig config) {
        Objects.requireNonNull(callId, "callId must not be null");
        Objects.requireNonNull(config, "config must not be null");
        sessions.put(callId, new CallSessionContext(callId, config));
    }

    public void closeCallSession(String callId) {
        if (callId != null) {
            sessions.remove(callId);
        }
    }

    public int getActiveSessionCount() {
        return sessions.size();
    }

    /**
     * Outbound Pipeline Hook (PCM16LE): Processes 24 kHz PCM16LE audio generated by the voice model,
     * queues the 8 kHz reference frame for AEC, and returns 8 kHz PCM16LE bytes for the telephony leg.
     */
    public byte[] onOutboundModelAudio24kHz(String callId, byte[] pcm24kHzLe) {
        CallSessionContext ctx = getOrCreateSession(callId);
        short[] samples24k = TelephonyAudioCodec.pcm16LeBytesToShorts(pcm24kHzLe);
        short[] samples8k = TelephonyAudioCodec.downsample24kHzTo8kHz(samples24k);
        ctx.enqueueFarEndSamples8k(samples8k);
        return TelephonyAudioCodec.shortsToPcm16LeBytes(samples8k);
    }

    /**
     * Outbound Pipeline Hook (G.711 u-law): Processes 24 kHz PCM16LE audio from the voice model,
     * queues the quantized 8 kHz reference for AEC, and returns G.711 u-law (PCMU) bytes for RTP.
     */
    public byte[] onOutboundModelAudio24kHzToUlaw(String callId, byte[] pcm24kHzLe) {
        CallSessionContext ctx = getOrCreateSession(callId);
        short[] samples24k = TelephonyAudioCodec.pcm16LeBytesToShorts(pcm24kHzLe);
        short[] samples8k = TelephonyAudioCodec.downsample24kHzTo8kHz(samples24k);
        byte[] ulawBytes = TelephonyAudioCodec.encodeG711Ulaw(samples8k);
        short[] quantizedReference8k = TelephonyAudioCodec.decodeG711Ulaw(ulawBytes);
        ctx.enqueueFarEndSamples8k(quantizedReference8k);
        return ulawBytes;
    }

    /**
     * Inbound Pipeline Hook (PCM16LE): Processes a 20 ms (320-byte) 8 kHz PCM16LE frame from
     * the telephony gateway and returns the echo-cancelled 16 kHz PCM16LE payload for the model.
     */
    public ProcessedFrame onInboundCallerAudio8kHz(String callId, byte[] callerPcm8kHzLe) {
        CallSessionContext ctx = getOrCreateSession(callId);
        short[] near8k = TelephonyAudioCodec.pcm16LeBytesToShorts(callerPcm8kHzLe);
        return ctx.processNearEndSamples(near8k);
    }

    /**
     * Inbound Pipeline Hook (G.711 u-law): Processes a 20 ms (160-byte) G.711 u-law RTP payload
     * from the telephony gateway and returns the echo-cancelled 16 kHz PCM16LE payload for the model.
     */
    public ProcessedFrame onInboundCallerG711Ulaw(String callId, byte[] callerUlawBytes) {
        CallSessionContext ctx = getOrCreateSession(callId);
        short[] near8k = TelephonyAudioCodec.decodeG711Ulaw(callerUlawBytes);
        return ctx.processNearEndSamples(near8k);
    }

    private CallSessionContext getOrCreateSession(String callId) {
        Objects.requireNonNull(callId, "callId must not be null");
        return sessions.computeIfAbsent(callId, id -> new CallSessionContext(id, AecConfig.defaults()));
    }

    private static final class CallSessionContext {
        private final String callId;
        private final AcousticEchoCanceller aec;
        private final int frameSize;
        private final Deque<short[]> farEndFrameQueue = new ArrayDeque<>();

        private CallSessionContext(String callId, AecConfig config) {
            this.callId = callId;
            this.aec = new AcousticEchoCanceller(config);
            this.frameSize = config.getFrameSizeSamples();
        }

        private synchronized void enqueueFarEndSamples8k(short[] samples8k) {
            int offset = 0;
            while (offset + frameSize <= samples8k.length) {
                short[] frame = new short[frameSize];
                System.arraycopy(samples8k, offset, frame, 0, frameSize);
                farEndFrameQueue.addLast(frame);
                offset += frameSize;
            }
            while (farEndFrameQueue.size() > 100) {
                farEndFrameQueue.removeFirst();
            }
        }

        private synchronized ProcessedFrame processNearEndSamples(short[] near8k) {
            short[] farFrame = farEndFrameQueue.pollFirst();
            if (farFrame == null) {
                farFrame = new short[frameSize];
            }
            AcousticEchoCanceller.AecFrameResult result = aec.processFrame(near8k, farFrame);
            return new ProcessedFrame(
                    callId,
                    result.getCleaned16kHzPcmLeBytes(),
                    result.getCleaned8kHzPcmLeBytes(),
                    result);
        }
    }

    public static final class ProcessedFrame {
        private final String callId;
        private final byte[] clean16kHzPcmLe;
        private final byte[] clean8kHzPcmLe;
        private final AcousticEchoCanceller.AecFrameResult aecResult;

        public ProcessedFrame(
                String callId,
                byte[] clean16kHzPcmLe,
                byte[] clean8kHzPcmLe,
                AcousticEchoCanceller.AecFrameResult aecResult) {
            this.callId = callId;
            this.clean16kHzPcmLe = clean16kHzPcmLe;
            this.clean8kHzPcmLe = clean8kHzPcmLe;
            this.aecResult = aecResult;
        }

        public String getCallId() {
            return callId;
        }

        /**
         * Returns the echo-cancelled 16 kHz, 16-bit signed little-endian mono PCM bytes
         * ready to stream directly into the downstream voice model ({@code audio/pcm;rate=16000}).
         */
        public byte[] getClean16kHzPcmLe() {
            return clean16kHzPcmLe;
        }

        public byte[] getClean8kHzPcmLe() {
            return clean8kHzPcmLe;
        }

        public AcousticEchoCanceller.AecFrameResult getAecResult() {
            return aecResult;
        }
    }

    /**
     * Runnable CLI demonstration of the Server-Side AEC Pipeline Service across
     * Far-End Single-Talk (Echo Convergence), Caller Barge-In (Double-Talk), and Caller Single-Talk.
     */
    public static void main(String[] args) {
        System.out.println("================================================================================");
        System.out.println(" Server-Side Telephony Acoustic Echo Cancellation (AEC) Pipeline Demo");
        System.out.println("================================================================================");

        TelephonyAecPipelineService pipeline = new TelephonyAecPipelineService();
        String callId = "call-session-1001";
        pipeline.registerCallSession(callId, AecConfig.defaults());

        int totalFrames = 100; // 2.0 seconds (100 x 20 ms RTP frames)
        short[][] far8kHistory = new short[totalFrames][160];

        System.out.printf("%-10s | %-26s | %-10s | %-10s | %-11s | %-10s%n",
                "Time (ms)", "Call Phase", "Delay (ms)", "ERLE (dB)", "DoubleTalk", "Barge-In");
        System.out.println("--------------------------------------------------------------------------------");

        for (int f = 0; f < totalFrames; f++) {
            boolean agentSpeaking = (f < 80);
            boolean callerBargeIn = (f >= 55 && f < 75);
            boolean callerSingleTalk = (f >= 80);

            // 1. Outbound Hook: Voice model emits 24 kHz PCM16LE (480 samples per 20 ms)
            short[] model24k = new short[480];
            if (agentSpeaking) {
                for (int i = 0; i < 480; i++) {
                    int n = f * 480 + i;
                    long seed = (n * 1103515245L + 12345L) & 0x7FFFFFFFL;
                    double noise = ((seed / (double) 0x3FFFFFFFL) - 1.0);
                    double voice = 0.5 * Math.sin(2.0 * Math.PI * 420.0 * n / 24000.0)
                            + 0.3 * Math.cos(2.0 * Math.PI * 1100.0 * n / 24000.0);
                    model24k[i] = TelephonyAudioCodec.clampToShort(Math.round(8500.0 * (0.5 * noise + 0.5 * voice)));
                }
            }
            byte[] outbound8kBytes = pipeline.onOutboundModelAudio24kHz(
                    callId, TelephonyAudioCodec.shortsToPcm16LeBytes(model24k));
            far8kHistory[f] = TelephonyAudioCodec.pcm16LeBytesToShorts(outbound8kBytes);

            // 2. Simulate 60 ms (3 frames) network/gateway delay + multi-tap acoustic echo + caller voice
            short[] inbound8k = new short[160];
            for (int i = 0; i < 160; i++) {
                double echo = 0.0;
                if (f >= 3) {
                    short[] delayed = far8kHistory[f - 3];
                    echo = 0.40 * delayed[i]
                            + (i >= 6 ? -0.18 * delayed[i - 6] : 0.0)
                            + (i >= 18 ? 0.09 * delayed[i - 18] : 0.0);
                }
                double caller = 0.0;
                if (callerBargeIn || callerSingleTalk) {
                    int n = f * 160 + i;
                    caller = 9500.0 * (0.6 * Math.sin(2.0 * Math.PI * 210.0 * n / 8000.0)
                            + 0.4 * Math.sin(2.0 * Math.PI * 630.0 * n / 8000.0));
                }
                inbound8k[i] = TelephonyAudioCodec.clampToShort(Math.round(echo + caller));
            }

            // 3. Inbound Hook: Cancel echo & upsample to 16 kHz before sending to the voice model
            ProcessedFrame processed = pipeline.onInboundCallerAudio8kHz(
                    callId, TelephonyAudioCodec.shortsToPcm16LeBytes(inbound8k));
            AcousticEchoCanceller.AecFrameResult res = processed.getAecResult();

            if (f % 10 == 9) {
                String phase = callerSingleTalk
                        ? "Caller Single-Talk"
                        : (callerBargeIn ? "Caller Barge-In (DT)" : "Agent Single-Talk (Echo)");
                System.out.printf("%-10d | %-26s | %-10d | %-10.2f | %-11s | %-10s%n",
                        (f + 1) * 20,
                        phase,
                        res.getEstimatedBulkDelayMs(),
                        res.getErleDb(),
                        res.isDoubleTalkDetected(),
                        res.isBargeInTriggerRecommended());
            }
        }
        pipeline.closeCallSession(callId);
        System.out.println("================================================================================");
    }
}
